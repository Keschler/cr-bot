def _sequence_count(config: TimingConfig, family: str) -> int:
    total_weight = sum(config.family_weights.values())
    share = config.family_weights[family] / total_weight
    # Aim pool_factor * n_states candidates at ~5 captures per sequence.
    return max(4, int(round(config.pool_factor * config.n_states * share / 5.0)))


def generate_timing_pool(
    config: TimingConfig,
    live_hook: Callable[[Any, dict[str, Any], int], None] | None = None,
) -> list[dict[str, Any]]:
    """Generate the full candidate pool (unbalanced, deterministic).

    ``live_hook``, when given, is invoked with the live environment after
    every capture (before the next WAIT step), e.g. for counterfactual
    search on the exact labeled state.  Offsets passed to the hook match
    the post-hoc ``record["offset"]`` numbering.
    """

    context = _TimingContext.build(config.seed)
    pool: list[dict[str, Any]] = []
    for family in TIMING_FAMILIES:
        for seq_idx in range(_sequence_count(config, family)):
            try:
                captures = _BUILDERS[family](context, config, seq_idx, live_hook=live_hook)
            except TeacherError:
                continue
            for offset, record in enumerate(captures):
                record["offset"] = offset
                record["provenance"]["sequence_offset"] = offset
                record["provenance"]["sequence_length"] = len(captures)
                pool.append(record)
    return pool


def replay_timing_sequences(
    config: TimingConfig,
    selections: Sequence[tuple[str, int]],
    live_hook: Callable[[Any, dict[str, Any], int], None] | None = None,
) -> None:
    """Rebuild selected ``(family, seq_idx)`` sequences, invoking the hook.

    Replays are bit-deterministic: the same seeds rebuild the same
    environments, so a second pass observes the identical labeled states
    as the original pool pass (verified by state-hash comparison in the
    search dataset builder).
    """

    context = _TimingContext.build(config.seed)
    for family, seq_idx in selections:
        if family not in _BUILDERS:
            raise TeacherError(f"unknown timing family for replay: {family!r}")
        try:
            _BUILDERS[family](context, config, int(seq_idx), live_hook=live_hook)
        except TeacherError:
            continue


def _hash_order(seed: int, record: dict[str, Any]) -> int:
    return _stable_seed(seed, "order", record["seq_id"], record["offset"])


def balance_timing_pool(
    pool: list[dict[str, Any]], config: TimingConfig
) -> tuple[list[DistillationSample], dict[str, Any]]:
    """Deterministically select a quota-balanced subset of the pool.

    Constraints: mode split near ``mode_target``; every family at or above
    ``family_min_share``; every WAIT duration within
    [``duration_min``, ``duration_max``] of WAITs; WAITs without legal PLAY
    capped at ``max_wait_without_play_share``.
    """

    if not pool:
        raise TeacherError("timing pool is empty; cannot balance")
    n_total = min(config.n_states, len(pool))
    n_wait_target = int(round(n_total * config.mode_target))
    waits = sorted(
        (r for r in pool if r["mode"] == 0),
        key=lambda r: _hash_order(config.seed, r),
    )
    plays = sorted(
        (r for r in pool if r["mode"] == 1),
        key=lambda r: _hash_order(config.seed, r),
    )
    # Cap WAITs with no legal PLAY (broke leftovers); strategic WAITs with
    # legal options stay.  Deterministic: hash order decides survivors.
    with_play = [r for r in waits if r["play_legal"]]
    without_play = [r for r in waits if not r["play_legal"]]
    keep_without = min(len(without_play), int(round(n_wait_target * config.max_wait_without_play_share)))
    waits = sorted(with_play + without_play[:keep_without], key=lambda r: _hash_order(config.seed, r))
    if len(waits) < n_wait_target:
        raise TeacherError(
            f"timing pool holds only {len(waits)} usable WAITs for {n_wait_target} requested"
        )

    # Duration quotas: equal shares sit inside every [min, max] band.
    per_duration = n_wait_target // 4
    by_duration: dict[int, list[dict[str, Any]]] = {d: [] for d in range(4)}
    for record in waits:
        by_duration[record["duration"]].append(record)
    for duration, rows in by_duration.items():
        if len(rows) < per_duration:
            raise TeacherError(
                f"duration {duration} has {len(rows)} WAITs, need {per_duration}"
            )
    selected_waits: list[dict[str, Any]] = []
    for duration in range(4):
        selected_waits.extend(by_duration[duration][:per_duration])
    # Fill remainder (rounding) from the scarcest durations first.
    remainder = n_wait_target - len(selected_waits)
    if remainder:
        counts = {d: per_duration for d in range(4)}
        taken = {id(r) for r in selected_waits}
        leftovers = [r for r in waits if id(r) not in taken]
        leftovers.sort(key=lambda r: (counts[r["duration"]], _hash_order(config.seed, r)))
        for record in leftovers[:remainder]:
            selected_waits.append(record)
            counts[record["duration"]] += 1

    n_play_target = n_total - len(selected_waits)
    if len(plays) < n_play_target:
        raise TeacherError(
            f"timing pool holds only {len(plays)} PLAYs for {n_play_target} requested"
        )
    # Family-stratified PLAY picks (round-robin over hash-ordered families).
    by_family: dict[str, list[dict[str, Any]]] = {f: [] for f in TIMING_FAMILIES}
    for record in plays:
        by_family[record["family"]].append(record)
    selected_plays: list[dict[str, Any]] = []
    while len(selected_plays) < n_play_target:
        progressed = False
        for family in TIMING_FAMILIES:
            if len(selected_plays) >= n_play_target:
                break
            rows = by_family[family]
            if len(rows) > len([r for r in selected_plays if r["family"] == family]):
                selected_plays.append(
                    rows[len([r for r in selected_plays if r["family"] == family])]
                )
                progressed = True
        if not progressed:
            break

    selected = selected_waits + selected_plays
    stats = _pool_stats(selected)
    _assert_balance(stats, config, n_total)
    samples = [_to_sample(record, index) for index, record in enumerate(selected)]
    return samples, stats


def _pool_stats(selected: list[dict[str, Any]]) -> dict[str, Any]:
    from collections import Counter

    waits = [r for r in selected if r["mode"] == 0]
    families = Counter(r["family"] for r in selected)
    durations = Counter(r["duration"] for r in waits)
    two_plus = sum(1 for r in waits if r["legal_cards"] >= 2)
    return {
        "n": len(selected),
        "n_wait": len(waits),
        "n_play": len(selected) - len(waits),
        "wait_share": len(waits) / max(1, len(selected)),
        "family_share": {f: families.get(f, 0) / max(1, len(selected)) for f in TIMING_FAMILIES},
        "family_n": dict(families),
        "duration_share": {d: durations.get(d, 0) / max(1, len(waits)) for d in range(4)},
        "duration_n": {d: durations.get(d, 0) for d in range(4)},
        "wait_with_play_share": sum(1 for r in waits if r["play_legal"]) / max(1, len(waits)),
        "wait_with_two_plus_share": two_plus / max(1, len(waits)),
    }


def _assert_balance(stats: dict[str, Any], config: TimingConfig, n_total: int) -> None:
    problems: list[str] = []
    if abs(stats["wait_share"] - config.mode_target) > config.mode_tol + 1e-9:
        problems.append(f"mode split {stats['wait_share']:.3f} outside target")
    for family, share in stats["family_share"].items():
        if share < config.family_min_share - 1e-9:
            problems.append(f"family {family} share {share:.3f} below minimum")
    for duration, share in stats["duration_share"].items():
        if not (config.duration_min - 1e-9 <= share <= config.duration_max + 1e-9):
            problems.append(f"duration {duration} share {share:.3f} outside band")
    if stats["wait_with_play_share"] < 0.70 - 1e-9:
        problems.append("WAIT-with-legal-PLAY below 0.70")
    if stats["wait_with_two_plus_share"] < 0.40 - 1e-9:
        problems.append("WAIT-with-2+-cards below 0.40")
    if problems:
        raise TeacherError("timing balance unsatisfiable: " + "; ".join(problems))


def _to_sample(record: dict[str, Any], index: int) -> DistillationSample:
    provenance = dict(record["provenance"])
    provenance["index"] = index
    return DistillationSample(
        family=record["family"],
        raster=record["raster"],
        global_features=record["global_features"],
        entity_tokens=record["entity_tokens"],
        entity_mask=record["entity_mask"],
        hand_tokens=record["hand_tokens"],
        opp_hand_probs=_uniform_belief(),
        opp_out_of_cycle=_empty_out_of_cycle(),
        opp_elixir_interval=np.asarray([0.0, 10.0], dtype=np.float32),
        event_history=np.zeros((16, 8), dtype=np.float32),
        legal_play=record["legal_play"],
        legal_wait=record["legal_wait"],
        own_elixir=record["own_elixir"],
        target=record["target"],
        soft_placement=record["soft_placement"],
        provenance=provenance,
    )


_BELIEF_CACHE: dict[str, np.ndarray] = {}


def _uniform_belief() -> np.ndarray:
    cached = _BELIEF_CACHE.get("probs")
    if cached is None:
        cached = np.full((128,), 1.0 / 128, dtype=np.float32)
        _BELIEF_CACHE["probs"] = cached
    return np.array(cached, dtype=np.float32)


def _empty_out_of_cycle() -> np.ndarray:
    return np.zeros((128,), dtype=bool)


def generate_timing_dataset(config: TimingConfig) -> tuple[list[DistillationSample], dict[str, Any]]:
    """Generate a quota-balanced timing dataset and its balance report."""

    pool = generate_timing_pool(config)
    return balance_timing_pool(pool, config)


def generate_timing_natural(config: TimingConfig) -> tuple[list[DistillationSample], dict[str, Any]]:
    """Generate an unbalanced natural-distribution timing set.

    Same sequence generator, no quota selection: the pool in deterministic
    hash order (representative of pool composition), truncated to
    ``n_states``.  This mirrors what real rollouts yield.
    """

    pool = generate_timing_pool(config)
    pool.sort(key=lambda r: _hash_order(config.seed + 999_983, r))
    selected = pool[: min(config.n_states, len(pool))]
    if not selected:
        raise TeacherError("timing pool is empty; cannot build natural set")
    stats = _pool_stats(selected)
    return [_to_sample(record, index) for index, record in enumerate(selected)], stats


def describe_pool(config: TimingConfig) -> dict[str, Any]:
    """Report raw pool composition (quota diagnostics, no selection)."""

    return _pool_stats(generate_timing_pool(config))


