"""Real-simulator timing curriculum for V4 Stage 1 (2.6 Hog WAIT/PLAY timing).

The natural simulator distribution is ~96.6% PLAY, so mode/duration heads
are never meaningfully tested.  This module builds a dedicated *balanced*
timing dataset from short temporal sequences generated by real simulator
rollouts, labeled by the timing teacher (:mod:`rl.timing_teacher`).

Design rules (enforced, not aspirational):

* Every elixir/threat/hand modification happens in authoritative simulator
  state FIRST; observations are regenerated afterwards via
  ``observe_v2_for_viewer``, so elixir scalar, raster, entities, hand, and
  legal masks stay internally consistent.  Public feature vectors are never
  patched directly.
* WAITs are strategic (rich elixir, legal PLAYs available, wrong moment),
  not broke states.  The quota balancer caps WAITs without legal PLAY.
* Sequences cross one teacher decision boundary (elixir affordability,
  threat-distance window, match clock), producing WAIT* -> PLAY switches
  from the same rollout: ``3.5 -> WAIT, 3.9 -> WAIT, 4.0 -> PLAY Hog``.
* Everything is deterministic per ``(seed, family, sequence)``: fresh
  environments, hash-derived setpoints, frozen WAIT-only opponent.

Six timing families (2.6 Hog, fixed player deck):

* ``opening-scout``: match start, 9-10 elixir, brief scouting hold (T1).
* ``preserve-defense``: ground threat, Cannon in hand but unaffordable
  while cheap is playable; WAIT for Cannon (T5).  Includes unanswerable-air
  variants (rich, wrong answers) for high-elixir WAIT coverage.
* ``counterpush-save``: surviving Musketeer, quiet board, Hog in hand but
  unaffordable; WAIT until Hog is affordable, then counterpush (T3/T4).
* ``defensive-timing``: Cannon affordable, threat still outside the
  placement window; WAIT until it enters (T2).  Elixir held sufficient so
  timing depends on position, not affordability.
* ``hold-utility``: spells affordable but low-value (dispersed targets);
  WAIT until a cluster is worth the Fireball/Log, or until elixir crosses a
  spell-affordability boundary into a clustered state.
* ``avoid-overcommit``: own Hog pushing, elixir below the cycle threshold;
  WAIT instead of adding support (T4), sometimes ending in defense when a
  threat arrives.

Consumers see ``DistillationSample`` + ``to_torch_batch`` unchanged; timing
metadata (family, sequence id/offset, legal-card counts, teacher duration)
travels in ``provenance``.
"""

