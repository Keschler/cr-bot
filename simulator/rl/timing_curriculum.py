_Y_HOLD = 0.60
_SCOUT_SECONDS = 0.75
_MAX_SEQ_STEPS = 10


def _stable_seed(seed: int, *parts: object) -> int:
    payload = "\x1f".join((str(seed), *(str(part) for part in parts))).encode()
    return int.from_bytes(hashlib.sha256(payload).digest()[:8], "big")


@dataclass(frozen=True, slots=True)
class TimingConfig:
    """Target size and balance contract for the timing dataset."""

    n_states: int
    seed: int
    family_weights: dict[str, float] | None = None
    pool_factor: int = 3
    mode_target: float = 0.5
    mode_tol: float = 0.03
    family_min_share: float = 0.10
    duration_min: float = 0.15
    duration_max: float = 0.40
    max_wait_without_play_share: float = 0.30

    def __post_init__(self) -> None:
        if type(self.n_states) is not int or self.n_states <= 0:
            raise ValueError("n_states must be a positive integer")
        if type(self.seed) is not int or self.seed < 0:
            raise ValueError("seed must be a non-negative integer")
        weights = dict(_DEFAULT_FAMILY_WEIGHTS) if self.family_weights is None else dict(self.family_weights)
        if set(weights) != set(TIMING_FAMILIES):
            raise ValueError(f"family_weights must cover exactly {TIMING_FAMILIES}")
        if any(not isinstance(w, float) or w <= 0.0 for w in weights.values()):
            raise ValueError("family_weights values must be positive floats")
        object.__setattr__(self, "family_weights", weights)
        if type(self.pool_factor) is not int or self.pool_factor < 1:
            raise ValueError("pool_factor must be a positive integer")


@dataclass
class _TimingContext:
    """Shared read-only simulator state for one timing-generation run."""

    ruleset: Any
    pool: OpponentPool
    tick_us: int

    @classmethod
    def build(cls, seed: int) -> "_TimingContext":
        ruleset = load_fixed_ruleset()
        return cls(ruleset=ruleset, pool=OpponentPool(ruleset, seed=seed), tick_us=int(ruleset.tick_us))


# ---------------------------------------------------------------------------
# Authoritative-state construction helpers.
#
# Everything here mutates BattleState BEFORE any observation is built, so all
# derived tensors stay consistent.  Nothing patches feature vectors.
# ---------------------------------------------------------------------------


def _set_hand(state: Any, player: int, keys: tuple[str, ...] | list[str]) -> None:
    """Arrange the player's hand deterministically (deck stays consistent)."""

    keys = list(keys)
    if len(keys) != 4 or len(set(keys)) != 4:
        raise TeacherError("timing hand must hold four distinct cards")
    player_state = state.players[player]
    if any(card not in player_state.deck for card in keys):
        raise TeacherError(f"timing hand {keys} outside the player deck")
    rest = [card for card in player_state.deck if card not in keys]
    player_state.hand = list(keys)
    player_state.draw_pile = rest
    player_state.next_card_cooldown_us = 0


def _set_elixir(state: Any, player: int, milli: int) -> None:
    if milli < 0 or milli > 10_000:
        raise TeacherError(f"elixir setpoint {milli} out of range")
    player_state = state.players[player]
    player_state.elixir_milli = int(milli)
    player_state.elixir_remainder = 0


def _pick_cell(cells: Any, col: int, row: int) -> tuple[int, int]:
    if not cells:
        raise TeacherError("no legal deployment cell for setup card")
    return min(
        cells,
        key=lambda cell: (abs(cell[0] - col) + abs(cell[1] - row), cell[1], cell[0]),
    )


def _deploy(
    context: _TimingContext,
    state: Any,
    engine: Any,
    player: int,
    card: str,
    col: int,
    row: int,
) -> None:
    """Deploy one setup card through the authoritative action path."""

    try:
        from ..actions import PlayCardAction
    except ImportError:  # pragma: no cover - top-level ``rl`` imports
        from simulator.actions import PlayCardAction
    player_state = state.players[player]
    if card not in player_state.deck:
        raise TeacherError(f"setup card {card!r} absent from the deck")
    player_state.elixir_milli = 10_000
    player_state.elixir_remainder = 0
    player_state.next_card_cooldown_us = 0
    hand = list(player_state.hand)
    if card in hand:
        slot = hand.index(card)
    else:
        draw_index = player_state.draw_pile.index(card)
        slot = 0
        player_state.hand[slot], player_state.draw_pile[draw_index] = (
            player_state.draw_pile[draw_index],
            player_state.hand[slot],
        )
    cell = _pick_cell(engine.legal_cells(state, player, card), col, row)
    result = engine.apply_actions(state, (PlayCardAction(player, slot, cell),))
    if len(result) != 1 or not result[0].accepted:
        raise TeacherError(f"setup deploy of {card!r} rejected: {result[0].reason if result else None}")
    state.players[0].next_card_cooldown_us = 0
    state.players[1].next_card_cooldown_us = 0


def _live_enemies(state: Any, owner: int = 1) -> list[Any]:
    return [
        entity
        for entity in state.entities.values()
        if entity.alive and entity.owner == owner and entity.kind != "tower"
    ]


def _live_own_troops(state: Any) -> list[Any]:
    return [
        entity
        for entity in state.entities.values()
        if entity.alive and entity.owner == 0 and entity.kind != "tower"
    ]


def _is_building_entity(context: _TimingContext, entity: Any) -> bool:
    card_id = getattr(entity, "card_id", "")
    try:
        definition = context.ruleset.card(card_id)
    except (KeyError, ValueError):
        return False
    return str(getattr(definition, "kind", "")) == "building"


def _live_own_musk_or_troop(state: Any, context: _TimingContext) -> list[Any]:
    return [e for e in _live_own_troops(state) if not _is_building_entity(context, e)]


# ---------------------------------------------------------------------------
# Environment scaffolding: wrapped scenarios or raw env, WAIT-stepped.
# ---------------------------------------------------------------------------


def _new_wrapped_env(context: _TimingContext, source: str, opponent_cards: tuple[str, ...], seed: int) -> Any:
    try:
        from ..engine import BattleEngine
        from ..env import SimulatorEnv
    except ImportError:  # pragma: no cover - top-level ``rl`` imports
        from simulator.engine import BattleEngine
        from simulator.env import SimulatorEnv
    base = SimulatorEnv(
        engine=BattleEngine(context.ruleset, validate_every_tick=False),
        decision_interval_us=250_000,
    )
    wrapped = BasicMechanicsScenarioEnv(
        base,
        BasicScenarioConfig(source=source, target_player=0, decision_limit=64),
    )
    wrapped.reset_v2(
        seed=seed,
        decks=(tuple(ROSTER_PLAYER_DECK), tuple(opponent_cards)),
        shuffle_decks=True,
    )
    return wrapped


def _new_raw_env(context: _TimingContext, opponent_cards: tuple[str, ...], seed: int) -> Any:
    try:
        from ..engine import BattleEngine
        from ..env import SimulatorEnv
    except ImportError:  # pragma: no cover - top-level ``rl`` imports
        from simulator.engine import BattleEngine
        from simulator.env import SimulatorEnv
    env = SimulatorEnv(
        engine=BattleEngine(context.ruleset, validate_every_tick=False),
        decision_interval_us=250_000,
    )
    env.reset_v2(
        seed=seed,
        decks=(tuple(ROSTER_PLAYER_DECK), tuple(opponent_cards)),
        shuffle_decks=True,
    )
    return env


def _step_wait(env: Any) -> None:
    try:
        from ..actions import WaitAction
    except ImportError:  # pragma: no cover - top-level ``rl`` imports
        from simulator.actions import WaitAction
    env.step_v2((WaitAction(0), WaitAction(1)))


# ---------------------------------------------------------------------------
# Capture + label.
# ---------------------------------------------------------------------------


def _capture(
    context: _TimingContext,
    env: Any,
    *,
    family: str,
    seq_id: str,
    offset: int,
    env_seed: int,
    source: str,
) -> dict[str, Any] | None:
    """Observe, label, and package one decision point (None if unusable)."""

    state = env.state
    if state is None or state.terminal:
        return None
    try:
        observation = env.observe_v2_for_viewer(0)
    except (ValueError, TypeError):
        return None
    player_state = state.players[0]
    hand = list(player_state.hand)
    if len(hand) != 4:
        return None
    elixir = float(player_state.elixir_milli) / 1000.0
    try:
        hand_tokens = build_hand_tokens(hand, elixir)
    except TeacherError:
        return None
    legal_play = np.array(observation.legal_play, dtype=bool)
    tick_seconds = float(state.tick) * float(context.tick_us) / 1_000_000.0
    try:
        target = timing_teacher_label(
            hand_tokens=hand_tokens,
            entity_tokens=np.asarray(observation.entity_tokens),
            entity_mask=np.asarray(observation.entity_mask),
            legal_play=legal_play,
            legal_wait=bool(observation.legal_wait),
            own_elixir=elixir,
            tick_seconds=tick_seconds,
            y_hold=_Y_HOLD,
            scout_seconds=_SCOUT_SECONDS,
        )
    except TeacherError:
        return None
    if target.mode == 1:
        try:
            soft = soft_placement_target(
                target.row, target.col, np.asarray(legal_play[target.card_slot])
            )
        except TeacherError:
            return None
    else:
        soft = np.zeros((32, 18), dtype=np.float32)
    legal_cards = int(np.asarray(legal_play).reshape(4, -1).any(axis=1).sum())
    return {
        "family": family,
        "raster": np.array(observation.board, dtype=np.float32),
        "global_features": np.array(observation.global_vector, dtype=np.float32),
        "entity_tokens": np.array(observation.entity_tokens, dtype=np.float32),
        "entity_mask": np.array(observation.entity_mask, dtype=bool),
        "hand_tokens": hand_tokens,
        "legal_play": legal_play,
        "legal_wait": bool(observation.legal_wait),
        "own_elixir": float(elixir),
        "target": target,
        "soft_placement": soft,
        "mode": int(target.mode),
        "duration": int(target.wait_duration_idx),
        "card_slot": int(target.card_slot),
        "seq_id": seq_id,
        "offset": int(offset),
        "legal_cards": legal_cards,
        "play_legal": bool(legal_cards > 0),
        "provenance": {
            "generator": TIMING_GENERATOR_VERSION,
            "teacher": TIMING_TEACHER_VERSION,
            "timing_family": family,
            "seq_id": seq_id,
            "sequence_offset": int(offset),
            "env_seed": int(env_seed),
            "state_hash": state.state_hash(),
            "source": source,
            "target_elixir_milli": int(player_state.elixir_milli),
            "target_hand": list(hand),
            "legal_cards": legal_cards,
            "teacher_mode": int(target.mode),
            "teacher_card_slot": int(target.card_slot),
            "teacher_wait_duration": int(target.wait_duration_idx),
            "play_legal_during_wait": bool(legal_cards > 0),
            "tick_seconds": round(tick_seconds, 3),
        },
    }


# ---------------------------------------------------------------------------
# Six family constructors.  Each returns a list of capture dicts (possibly
# empty when postconditions fail); all randomness derives from seeds.
# ---------------------------------------------------------------------------


def _build_opening(
    context: _TimingContext, config: TimingConfig, seq_idx: int,
    live_hook: Callable[[Any, dict[str, Any], int], None] | None = None,
) -> list[dict[str, Any]]:
    env_seed = _stable_seed(config.seed, "timing", "opening-scout", seq_idx)
    env = _new_raw_env(context, tuple(ROSTER_PLAYER_DECK), env_seed)
    elixir = 9000 + (env_seed % 3) * 500
    _set_elixir(env.state, 0, elixir)
    seq_id = f"opening-scout:{seq_idx}"
    captures: list[dict[str, Any]] = []
    for offset in range(4):
        record = _capture(
            context, env, family="opening-scout", seq_id=seq_id,
            offset=offset, env_seed=env_seed, source="raw-opening",
        )
        if record is None:
            break
        captures.append(record)
        if live_hook is not None:
            live_hook(env, record, offset)
        _step_wait(env)
    return captures


def _build_preserve(
    context: _TimingContext, config: TimingConfig, seq_idx: int,
    live_hook: Callable[[Any, dict[str, Any], int], None] | None = None,
) -> list[dict[str, Any]]:
    env_seed = _stable_seed(config.seed, "timing", "preserve-defense", seq_idx)
    variant = (env_seed % 4 == 3)  # ~25%: unanswerable-air, rich WAITs
    source = "air-defense" if variant else "ground-defense"
    archetype = _FAMILY_ARCHETYPE["preserve-defense"] if not variant else "air-beatdown"
    opponent = context.pool.sample(seq_idx, archetype=archetype, strategy="deterministic-cycle")
    env = _new_wrapped_env(context, source, opponent.deck.cards, env_seed)
    state, engine = env.state, env.engine
    if variant:
        _set_hand(state, 0, ["hog-rider", "cannon", "skeletons", "ice-golem"])
        if seq_idx % 8 == 3:
            # Upper half of variants sit at 8-10k elixir, the only natural
            # source of duration-0 WAITs besides the opening family.
            _set_elixir(state, 0, 8000 + env_seed % 2001)
        else:
            _set_elixir(state, 0, 6000 + env_seed % 2001)
    else:
        _set_hand(state, 0, ["cannon", "skeletons", "hog-rider", "musketeer"])
        _set_elixir(state, 0, 2400 + env_seed % 500)
    engine.validate_state(state)
    seq_id = f"preserve-defense:{seq_idx}"
    captures: list[dict[str, Any]] = []
    for offset in range(_MAX_SEQ_STEPS):
        if not _live_enemies(state):
            break
        record = _capture(
            context, env, family="preserve-defense", seq_id=seq_id,
            offset=offset, env_seed=env_seed, source=source,
        )
        if record is None:
            break
        captures.append(record)
        if live_hook is not None:
            live_hook(env, record, offset)
        _step_wait(env)
        if env.state is None or env.state.terminal:
            break
        state = env.state
    return captures


def _build_counterpush(
    context: _TimingContext, config: TimingConfig, seq_idx: int,
    live_hook: Callable[[Any, dict[str, Any], int], None] | None = None,
) -> list[dict[str, Any]]:
    env_seed = _stable_seed(config.seed, "timing", "counterpush-save", seq_idx)
    opponent = context.pool.sample(
        seq_idx, archetype=_FAMILY_ARCHETYPE["counterpush-save"], strategy="deterministic-cycle"
    )
    env = _new_wrapped_env(context, "isolated-offense", opponent.deck.cards, env_seed)
    state, engine = env.state, env.engine
    lane_col = 3 if env_seed % 2 == 0 else 14
    _deploy(context, state, engine, 0, "musketeer", lane_col, 25 + env_seed % 3)
    _set_hand(state, 0, ["hog-rider", "skeletons", "ice-spirit", "ice-golem"])
    _set_elixir(state, 0, 3400 + env_seed % 500)
    engine.validate_state(state)
    seq_id = f"counterpush-save:{seq_idx}"
    captures: list[dict[str, Any]] = []
    for offset in range(_MAX_SEQ_STEPS):
        if _live_enemies(state) or not _live_own_musk_or_troop(state, context):
            break
        record = _capture(
            context, env, family="counterpush-save", seq_id=seq_id,
            offset=offset, env_seed=env_seed, source="isolated-offense",
        )
        if record is None:
            break
        captures.append(record)
        if live_hook is not None:
            live_hook(env, record, offset)
        if record["mode"] == 1:
            break  # counterpush committed; further states leave the pattern
        _step_wait(env)
        if env.state is None or env.state.terminal:
            break
        state = env.state
    return captures


def _build_defensive_timing(
    context: _TimingContext, config: TimingConfig, seq_idx: int,
    live_hook: Callable[[Any, dict[str, Any], int], None] | None = None,
) -> list[dict[str, Any]]:
    env_seed = _stable_seed(config.seed, "timing", "defensive-timing", seq_idx)
    opponent = context.pool.sample(
        seq_idx, archetype=_FAMILY_ARCHETYPE["defensive-timing"], strategy="deterministic-cycle"
    )
    seq_id = f"defensive-timing:{seq_idx}"
    captures: list[dict[str, Any]] = []
    if seq_idx % 2 == 0:
        # Scenario threat: prelude-advanced, often already near the window.
        env = _new_wrapped_env(context, "ground-defense", opponent.deck.cards, env_seed)
        state, engine = env.state, env.engine
        source = "ground-defense"
    else:
        # Custom far threat: tankiest ground troop deployed deep, so the
        # capture arc spans pre-threat -> hold -> placement window.
        ground = sorted(
            _ground_troops(context, tuple(opponent.deck.cards)),
            key=lambda card: (-_card_cost(context, card), card),
        )
        if not ground:
            return []
        env = _new_raw_env(context, tuple(opponent.deck.cards), env_seed)
        state, engine = env.state, env.engine
        _deploy(context, state, engine, 1, ground[0], 9, 8 + env_seed % 4)
        source = "raw-far-threat"
    _set_hand(state, 0, ["cannon", "musketeer", "fireball", "log"])
    _set_elixir(state, 0, 6000 + env_seed % 1001)
    engine.validate_state(state)
    for offset in range(_MAX_SEQ_STEPS):
        foes = [e for e in _live_enemies(state)]
        ground = [e for e in foes if not _is_air_entity(context, e)]
        if not ground:
            break
        record = _capture(
            context, env, family="defensive-timing", seq_id=seq_id,
            offset=offset, env_seed=env_seed, source=source,
        )
        if record is None:
            break
        captures.append(record)
        if live_hook is not None:
            live_hook(env, record, offset)
        _step_wait(env)
        if env.state is None or env.state.terminal:
            break
        state = env.state
    return captures


def _ground_troops(context: _TimingContext, deck: tuple[str, ...]) -> list[str]:
    return [
        card for card in _troop_cards(context, deck)
        if not _is_air_card(context, card)
    ]


def _card_cost(context: _TimingContext, card_id: str) -> int:
    try:
        return int(context.ruleset.card(card_id).elixir_milli)
    except (KeyError, ValueError, AttributeError):
        return 0


def _spawn_count(context: _TimingContext, card_id: str) -> int:
    try:
        return int(context.ruleset.card(card_id).spawn_count or 1)
    except (KeyError, ValueError, AttributeError):
        return 1


def _is_air_card(context: _TimingContext, card_id: str) -> bool:
    try:
        definition = context.ruleset.card(card_id)
    except (KeyError, ValueError):
        return False
    mechanics = getattr(definition, "mechanics", {}) or {}
    get = getattr(mechanics, "get", None)
    layer = get("movement_layer") if callable(get) else None
    if layer is not None:
        return str(layer) == "air"
    return bool(getattr(definition, "is_air", False))


def _is_air_entity(context: _TimingContext, entity: Any) -> bool:
    return _is_air_card(context, str(getattr(entity, "card_id", "")))


def _troop_cards(context: _TimingContext, deck: tuple[str, ...]) -> list[str]:
    troops = []
    for card_id in deck:
        try:
            definition = context.ruleset.card(card_id)
        except (KeyError, ValueError):
            continue
        if str(getattr(definition, "kind", "")) == "troop":
            troops.append(card_id)
    return troops


def _build_hold_utility(
    context: _TimingContext, config: TimingConfig, seq_idx: int,
    live_hook: Callable[[Any, dict[str, Any], int], None] | None = None,
) -> list[dict[str, Any]]:
    env_seed = _stable_seed(config.seed, "timing", "hold-utility", seq_idx)
    seq_id = f"hold-utility:{seq_idx}"
    captures: list[dict[str, Any]] = []
    if env_seed % 2 == 0:
        # Dispersed WAITs: two bodies deployed far apart and far back, so no
        # threat and no cluster exists; elixir is mid and Hog is out of hand,
        # so holding (including spell ammo) is correct.  As they walk into
        # threat range the arc ends in defense PLAYs.
        opponent = context.pool.sample(
            seq_idx, archetype=_FAMILY_ARCHETYPE["hold-utility"], strategy="deterministic-cycle"
        )
        troops = _troop_cards(context, tuple(opponent.deck.cards))
        if len(troops) < 2:
            return []
        env = _new_raw_env(context, tuple(opponent.deck.cards), env_seed)
        state, engine = env.state, env.engine
        _deploy(context, state, engine, 1, troops[0], 6, 4)
        _deploy(context, state, engine, 1, troops[1], 12, 9)
        _set_hand(state, 0, ["fireball", "log", "cannon", "musketeer"])
        _set_elixir(state, 0, 4000 + env_seed % 2001)
        engine.validate_state(state)
        source = "raw-dispersed"
        for offset in range(_MAX_SEQ_STEPS):
            if len(_live_enemies(state)) < 2:
                break
            record = _capture(
                context, env, family="hold-utility", seq_id=seq_id,
                offset=offset, env_seed=env_seed, source=source,
            )
            if record is None:
                break
            captures.append(record)
            if live_hook is not None:
                live_hook(env, record, offset)
            _step_wait(env)
            if env.state is None or env.state.terminal:
                break
            state = env.state
    else:
        # Clustered spell PLAYs: adjacent bodies, no threats, elixir ramps
        # into spell affordability (log at 2.0, fireball below 6.0).
        opponent = context.pool.sample(
            seq_idx, archetype=_FAMILY_ARCHETYPE["hold-utility"], strategy="deterministic-cycle"
        )
        log_play = env_seed % 4 < 2
        troops = _troop_cards(context, tuple(opponent.deck.cards))
        if log_play:
            # Log is a restricted spell (own half only) that cannot hit air.
            # Static pair just off the bridge: threats (y > 0.45) with no
            # affordable non-spell answer, so the spell rule answers Log.
            # (Pairs deployed exactly on the bridge row do not path; the
            # frozen stack is discarded in favor of row 13.)
            troops = sorted(
                troops,
                key=lambda card: (
                    _spawn_count(context, card) != 1,
                    _is_air_card(context, card),
                    -_card_cost(context, card),
                    card,
                ),
            )
            base_row = 13
        else:
            troops = sorted(troops, key=lambda card: (_spawn_count(context, card) != 1, card))
            base_row = 6 + env_seed % 5
        if len(troops) < 2:
            return []
        env = _new_raw_env(context, tuple(opponent.deck.cards), env_seed)
        state, engine = env.state, env.engine
        for card in troops[:2]:
            _deploy(context, state, engine, 1, card, 9, base_row)
        if log_play:
            _set_hand(state, 0, ["log", "hog-rider", "musketeer", "cannon"])
            _set_elixir(state, 0, 2000 + env_seed % 500)
        else:
            _set_hand(state, 0, ["fireball", "log", "hog-rider", "musketeer"])
            _set_elixir(state, 0, 3900 + env_seed % 100)
        engine.validate_state(state)
        for offset in range(10):
            if len(_live_enemies(state)) < 2:
                break
            record = _capture(
                context, env, family="hold-utility", seq_id=seq_id,
                offset=offset, env_seed=env_seed, source="raw-cluster",
            )
            if record is None:
                break
            captures.append(record)
            if live_hook is not None:
                live_hook(env, record, offset)
            if record["mode"] == 1:
                break
            _step_wait(env)
            if env.state is None or env.state.terminal:
                break
            state = env.state
    return captures


def _build_avoid_overcommit(
    context: _TimingContext, config: TimingConfig, seq_idx: int,
    live_hook: Callable[[Any, dict[str, Any], int], None] | None = None,
) -> list[dict[str, Any]]:
    env_seed = _stable_seed(config.seed, "timing", "avoid-overcommit", seq_idx)
    variant = seq_idx % 3 == 2  # threat-arrival variant ends in defense
    source = "ground-defense" if variant else "isolated-offense"
    opponent = context.pool.sample(
        seq_idx, archetype=_FAMILY_ARCHETYPE["avoid-overcommit"], strategy="deterministic-cycle"
    )
    env = _new_wrapped_env(context, source, opponent.deck.cards, env_seed)
    state, engine = env.state, env.engine
    lane_col = 4 if env_seed % 2 == 0 else 13
    _deploy(context, state, engine, 0, "hog-rider", lane_col, 17 + env_seed % 2)
    _set_hand(state, 0, ["cannon", "musketeer", "skeletons", "ice-golem"])
    _set_elixir(state, 0, 5000 + env_seed % 1501)
    engine.validate_state(state)
    seq_id = f"avoid-overcommit:{seq_idx}"
    captures: list[dict[str, Any]] = []
    for offset in range(_MAX_SEQ_STEPS):
        hogs = [
            e for e in _live_own_troops(state)
            if str(getattr(e, "card_id", "")).replace("_", "-") in ("hog-rider", "cursed-hog")
        ]
        if not hogs:
            break
        record = _capture(
            context, env, family="avoid-overcommit", seq_id=seq_id,
            offset=offset, env_seed=env_seed, source=source,
        )
        if record is None:
            break
        captures.append(record)
        if live_hook is not None:
            live_hook(env, record, offset)
        _step_wait(env)
        if env.state is None or env.state.terminal:
            break
        state = env.state
    return captures


_BUILDERS: dict[str, Callable[..., list[dict[str, Any]]]] = {
    "opening-scout": _build_opening,
    "preserve-defense": _build_preserve,
    "counterpush-save": _build_counterpush,
    "defensive-timing": _build_defensive_timing,
    "hold-utility": _build_hold_utility,
    "avoid-overcommit": _build_avoid_overcommit,
}


